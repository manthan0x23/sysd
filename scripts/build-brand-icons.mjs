// Bundles only the logos referenced in src/lib/catalog/iconMap.ts into a small generated module.
// Run: node scripts/build-brand-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const sets = { logos: require("@iconify-json/logos/icons.json"), "simple-icons": require("@iconify-json/simple-icons/icons.json") };
const src = readFileSync("src/lib/catalog/iconMap.ts", "utf8");
const ids = [...new Set([...src.matchAll(/"((?:logos|simple-icons):[a-z0-9-]+)"/g)].map((m) => m[1]))].sort();
const out = {}; const missing = [];
for (const id of ids) {
  const [set, name] = id.split(":");
  const s = sets[set]; const ic = s.icons[name] ?? (s.aliases?.[name] && s.icons[s.aliases[name].parent]);
  if (!ic) { missing.push(id); continue; }
  out[id] = { body: ic.body, w: ic.width ?? s.width ?? 16, h: ic.height ?? s.height ?? 16, mono: set === "simple-icons" };
}
writeFileSync("src/lib/catalog/brandIcons.generated.ts", `// Generated by scripts/build-brand-icons.mjs. Do not edit.\nexport const BRAND_ICONS: Record<string, { body: string; w: number; h: number; mono: boolean }> = ${JSON.stringify(out)};\n`);
console.log(`bundled ${Object.keys(out).length} icons; missing: ${missing.join(", ") || "none"}`);
